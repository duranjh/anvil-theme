#!/usr/bin/env python3
"""scripts/spec-cards.py — generate docs/spec/<slug>.md cards.

Joins two markdown tables by section file name:
  * docs/SPEC.md            §4.2 "Conversion sections"  (Section | Merchant sets | Shopper sees)
  * docs/DESIGN-sections.md §3   "Spec cards"           (Section | Purpose | Blocks | Key settings | JS | A11y / honesty | ~Lines)

SPEC rows carry human names ("Ticker (horizontal)"); DESIGN rows carry file
names (`anvil-ticker`). The NAME_MAP below is the join key; an unmatched row
on either side is reported and makes the run exit 1 (cards for matched rows
are still written). Every card opens with the standard header
"Build exactly this; ids and words are yours; follow CONVENTIONS".

Usage:
  scripts/spec-cards.py [--root DIR] [--only SLUG ...] [--check] [--list]
    --check  do not write; exit 1 if any card on disk differs from what
             would be generated (CI drift guard)
"""
import argparse
import os
import re
import sys

HEADER = "Build exactly this; ids and words are yours; follow CONVENTIONS"

# SPEC §4.2 section name -> section file name (DESIGN §3)
NAME_MAP = {
    "Ticker (horizontal)": "anvil-ticker",
    "Ticker (vertical)": "anvil-ticker-vertical",
    "Icon bar": "anvil-icon-bar",
    "Icons with content": "anvil-icon-content",
    "Comparison table": "anvil-compare-table",
    "Before/after slider": "anvil-before-after",
    "Testimonials": "anvil-testimonials",
    "Review wall": "anvil-review-wall",
    "Social-proof cards": "anvil-social-cards",
    "Image/video slider": "anvil-media-slider",
    "Stories strip": "anvil-stories",
    "Logo list": "anvil-logo-list",
    "Content tabs": "anvil-tabs",
    "Custom columns": "anvil-columns",
    "Product features (hotspots)": "anvil-hotspots",
    "Shoppable image": "anvil-shoppable-image",
    "Results / stats": "anvil-stats",
    "Pricing table": "anvil-pricing",
    "Promo popup": "anvil-popup",
    "Track order": "anvil-track-order",
    "Parallax hero": "anvil-hero-parallax",
    "Slideshow hero": "anvil-hero-slideshow",
    "Section divider": "anvil-divider",
    "Sections group": "anvil-group",
    "Scroll-to-top": "anvil-scroll-top",
    "Guarantee icons": "anvil-guarantees",
    "Bundle deals": "anvil-bundle",
    "Timeline": "anvil-timeline",
    "Scrolling images (marquee)": "anvil-image-marquee",
    "Feature grid": "anvil-feature-grid",
    "Gallery": "anvil-image-gallery",
    "Product videos": "anvil-product-videos",
    "Simple FAQ": "anvil-faq",
    "Theme colours preview": "anvil-palette-preview",
    "Music player": "anvil-audio",
}

CELL_SPLIT = re.compile(r"(?<!\\)\|")


def read(path):
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def find_table(text, heading_regex, label):
    """Return (header_cells, rows) of the first markdown table after the heading."""
    lines = text.splitlines()
    start = None
    for i, ln in enumerate(lines):
        if re.match(heading_regex, ln.strip()):
            start = i
            break
    if start is None:
        raise SystemExit(f"{label}: heading matching {heading_regex!r} not found")
    rows = []
    header = None
    in_table = False
    for ln in lines[start + 1:]:
        s = ln.strip()
        if s.startswith("|"):
            cells = [c.strip().replace("\\|", "|") for c in CELL_SPLIT.split(s.strip("|"))]
            if header is None:
                header = cells
                in_table = True
                continue
            if all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
                continue  # separator
            rows.append(cells)
        elif in_table and s == "":
            break
        elif in_table:
            break
    if header is None:
        raise SystemExit(f"{label}: no table found after the heading")
    return header, rows


def normalise(name):
    name = re.sub(r"\(.*?\)", " ", name)
    return re.sub(r"[^a-z0-9]+", " ", name.lower()).strip()


def fuzzy_match(spec_name, design_slugs):
    tokens = set(normalise(spec_name).split())
    best, best_score = None, 0
    for slug in design_slugs:
        words = set(slug[len("anvil-"):].split("-"))
        score = len(tokens & words)
        if score > best_score:
            best, best_score = slug, score
    return best if best_score > 0 else None


def card_text(slug, spec_name, spec_row, design_row, spec_header, design_header):
    short = slug[len("anvil-"):]
    out = []
    out.append(f"# {slug} — spec card")
    out.append("")
    out.append(f"**{HEADER}.**")
    out.append("")
    out.append("_Generated by `scripts/spec-cards.py` from `docs/SPEC.md` §4.2 and `docs/DESIGN-sections.md` §3. Do not edit by hand; change the source tables and regenerate._")
    out.append("")
    out.append(f"## SPEC.md §4.2 — \"{spec_name}\"")
    out.append("")
    for h, cell in zip(spec_header[1:], spec_row[1:]):
        out.append(f"- **{h}:** {cell}")
    out.append("")
    out.append("## DESIGN-sections.md §3")
    out.append("")
    for h, cell in zip(design_header[1:], design_row[1:]):
        label = h.replace("beyond C", "beyond the chassis")
        out.append(f"- **{label}:** {cell}")
    out.append("")
    out.append("Legend: C = chassis settings (CONVENTIONS §4); L = local section blocks; T = theme blocks (`@theme`); SL = `<anvil-slider>`; MQ = `<anvil-marquee>`.")
    out.append("")
    out.append("## Files you may create or change")
    out.append("")
    out.append(f"- `sections/{slug}.liquid`")
    out.append(f"- `blocks/_{slug}-*.liquid` (only when the Blocks column names a private theme block)")
    out.append(f"- `assets/{slug}*.css` / `assets/{slug}*.js` (only when the JS column needs it)")
    out.append(f"- `docs/sections/{short}.md`")
    out.append("")
    out.append("## Non-negotiables")
    out.append("")
    out.append("- Skeleton, the 13 chassis settings and `presets` exactly as CONVENTIONS §3–§4; `{{ block.shopify_attributes }}` on every local block.")
    out.append("- Honesty rules (CONVENTIONS §10, docs/HONEST.md) are product requirements; every setting that could mislead carries a one-sentence `info`.")
    out.append("- Default content reads as an example; placeholders via `placeholder_svg_tag`; images via `image_tag` with `widths`/`sizes`.")
    out.append(f"- Finish with `npm run gate -- {short}` and write `docs/sections/{short}.md`.")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=None)
    ap.add_argument("--only", action="append", default=[], help="slug(s) to generate (with or without anvil-)")
    ap.add_argument("--check", action="store_true", help="verify cards on disk match; write nothing")
    ap.add_argument("--list", action="store_true", help="print the join table and exit")
    args = ap.parse_args()
    root = os.path.abspath(args.root or os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

    spec_path = os.path.join(root, "docs", "SPEC.md")
    design_path = os.path.join(root, "docs", "DESIGN-sections.md")
    for p in (spec_path, design_path):
        if not os.path.isfile(p):
            raise SystemExit(f"{os.path.relpath(p, root)}:1: missing")

    spec_header, spec_rows = find_table(read(spec_path), r"^###\s*4\.2\b", "docs/SPEC.md")
    design_header, design_rows = find_table(read(design_path), r"^##\s*3\.\s*Spec cards", "docs/DESIGN-sections.md")

    design_by_slug = {}
    for row in design_rows:
        slug = row[0].strip("` ")
        if slug.startswith("anvil-"):
            design_by_slug[slug] = row

    only = {("anvil-" + s if not s.startswith("anvil-") else s) for s in (o.strip() for o in args.only)}
    problems = 0
    joined = []
    used = set()
    for row in spec_rows:
        name = row[0].strip()
        slug = NAME_MAP.get(name) or fuzzy_match(name, design_by_slug.keys())
        if slug is None or slug not in design_by_slug:
            print(f"docs/SPEC.md: no DESIGN row for section \"{name}\" (slug guess: {slug})", file=sys.stderr)
            problems += 1
            continue
        if slug in used:
            print(f"docs/SPEC.md: section \"{name}\" maps to {slug} which is already used", file=sys.stderr)
            problems += 1
            continue
        used.add(slug)
        joined.append((slug, name, row, design_by_slug[slug]))
    for slug in design_by_slug:
        if slug not in used:
            print(f"docs/DESIGN-sections.md: DESIGN row {slug} has no SPEC row", file=sys.stderr)
            problems += 1

    if args.list:
        for slug, name, _, _ in joined:
            print(f"{slug:28s} <- {name}")
        return 1 if problems else 0

    out_dir = os.path.join(root, "docs", "spec")
    written = 0
    drift = 0
    for slug, name, srow, drow in joined:
        if only and slug not in only:
            continue
        text = card_text(slug, name, srow, drow, spec_header, design_header)
        path = os.path.join(out_dir, f"{slug[len('anvil-'):]}.md")
        rel = os.path.relpath(path, root)
        if args.check:
            current = read(path) if os.path.isfile(path) else None
            if current != text:
                print(f"{rel}:1: card is missing or out of date; run scripts/spec-cards.py")
                drift += 1
            continue
        os.makedirs(out_dir, exist_ok=True)
        if not os.path.isfile(path) or read(path) != text:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text)
            written += 1

    if args.check:
        if drift or problems:
            print(f"spec-cards: {drift} stale card(s), {problems} join problem(s)", file=sys.stderr)
            return 1
        print(f"spec-cards: {len(joined)} cards up to date")
        return 0
    print(f"spec-cards: {len(joined)} sections joined, {written} card(s) written to docs/spec/")
    if problems:
        print(f"spec-cards: {problems} join problem(s); fix NAME_MAP or the tables", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
