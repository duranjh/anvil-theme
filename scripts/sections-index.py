#!/usr/bin/env python3
"""scripts/sections-index.py — generate docs/SECTIONS.md, the index of every section in the theme.

Read from the section schemas, the templates and the section groups, so the index never drifts from the code:
  * addable sections (a schema with presets): editor name, file, where it may be added (enabled_on / disabled_on,
    CONVENTIONS §4), what its blocks are (theme blocks, local block types, @app), the templates and groups that ship
    it, and its card in docs/sections/
  * template sections (main-*) and the sections that only live in a group or the layout
Merchant-facing descriptions stay in README "What's inside"; the design of each section is its card.

Usage:
  scripts/sections-index.py [--root DIR] [--check]
    --check  do not write; exit 1 when docs/SECTIONS.md differs from what would be generated (CI drift guard)
"""
import argparse
import glob
import json
import os
import re
import sys

SCHEMA_RE = re.compile(r"{%-?\s*schema\s*-?%}(.*?){%-?\s*endschema\s*-?%}", re.S)
OUT = "docs/SECTIONS.md"
GROUP_NAMES = {"header": "header", "footer": "footer", "custom.overlay": "overlay", "aside": "aside"}


def load_json(path):
    text = open(path, encoding="utf-8").read()
    # Shopify writes a /* ... */ banner on top of generated JSON files.
    text = re.sub(r"^\s*/\*.*?\*/", "", text, count=1, flags=re.S)
    return json.loads(text)


def schema_of(path):
    m = SCHEMA_RE.search(open(path, encoding="utf-8").read())
    return json.loads(m.group(1)) if m else None


def where(schema):
    en = (schema.get("enabled_on") or {})
    dis = (schema.get("disabled_on") or {})
    if en:
        parts = []
        if en.get("templates"):
            parts.append("templates: " + ", ".join(en["templates"]))
        if en.get("groups"):
            parts.append("groups: " + ", ".join(GROUP_NAMES.get(g, g) for g in en["groups"]))
        return "only " + "; ".join(parts)
    groups = dis.get("groups") or []
    templates = dis.get("templates") or []
    if "*" in groups:
        out = "templates only"
    elif groups:
        out = "templates and groups except " + ", ".join(GROUP_NAMES.get(g, g) for g in groups)
    else:
        out = "templates and every group"
    if templates:
        out += "; not on " + ", ".join(templates)
    return out


def blocks_of(schema):
    kinds = []
    local = []
    for b in schema.get("blocks") or []:
        t = b.get("type", "")
        if t == "@theme":
            kinds.append("theme blocks")
        elif t == "@app":
            kinds.append("app blocks")
        elif "name" in b:
            local.append(t)
        else:
            kinds.append("`" + t + "`")
    if local:
        kinds.insert(0, f"{len(local)} local ({', '.join(local[:6])}{', …' if len(local) > 6 else ''})")
    return "; ".join(kinds) or "none"


def shipped(root):
    """section type -> list of template / group names that ship it."""
    uses = {}
    files = sorted(glob.glob(os.path.join(root, "templates", "*.json")))
    files += sorted(glob.glob(os.path.join(root, "templates", "customers", "*.json")))
    files += sorted(glob.glob(os.path.join(root, "sections", "*-group.json")))
    for f in files:
        rel = os.path.relpath(f, root)
        name = rel.replace("templates/", "").replace("sections/", "").replace(".json", "")
        try:
            data = load_json(f)
        except (ValueError, OSError):
            continue
        for sec in (data.get("sections") or {}).values():
            label = name + (" (off)" if sec.get("disabled") else "")
            lst = uses.setdefault(sec.get("type"), [])
            if label not in lst:
                lst.append(label)
    return uses


def build(root):
    uses = shipped(root)
    addable, template_bound, other = [], [], []
    for path in sorted(glob.glob(os.path.join(root, "sections", "*.liquid"))):
        slug = os.path.basename(path)[:-7]
        schema = schema_of(path)
        if schema is None:
            continue
        row = (slug, schema)
        if schema.get("presets"):
            addable.append(row)
        elif slug.startswith("main-"):
            template_bound.append(row)
        else:
            other.append(row)

    lines = [
        "# Anvil — Sections",
        "",
        "_Generated by `scripts/sections-index.py` from the section schemas, templates and section groups; do not edit by hand (`--check` runs in `npm run lint`). What each section is for, in a merchant's words: README \"What's inside\". How each one is built: its card in `docs/sections/`. Group rules: CONVENTIONS §4._",
        "",
        f"## Sections you can add ({len(addable)})",
        "",
        "| Editor name | File | Can be added to | Blocks | Shipped in | Card |",
        "|---|---|---|---|---|---|",
    ]
    for slug, schema in sorted(addable, key=lambda r: r[1].get("name", r[0]).lower()):
        card_slug = slug[6:] if slug.startswith("anvil-") else slug
        card = f"[{card_slug}](sections/{card_slug}.md)" if os.path.exists(os.path.join(root, "docs", "sections", card_slug + ".md")) else "—"
        ship = ", ".join(uses.get(slug, [])) or "—"
        lines.append(f"| {schema.get('name', slug)} | `sections/{slug}.liquid` | {where(schema)} | {blocks_of(schema)} | {ship} | {card} |")

    lines += [
        "",
        f"## Template sections ({len(template_bound)})",
        "",
        "One per template, not in the Add section list.",
        "",
        "| Editor name | File | Blocks | Shipped in |",
        "|---|---|---|---|",
    ]
    for slug, schema in template_bound:
        ship = ", ".join(uses.get(slug, [])) or "—"
        lines.append(f"| {schema.get('name', slug)} | `sections/{slug}.liquid` | {blocks_of(schema)} | {ship} |")

    lines += [
        "",
        f"## Group, layout and helper sections ({len(other)})",
        "",
        "Rendered from a section group, `layout/theme.liquid` or the Section Rendering API; no preset, so they are not in the Add section list.",
        "",
        "| Editor name | File | Blocks | Shipped in |",
        "|---|---|---|---|",
    ]
    for slug, schema in other:
        ship = ", ".join(uses.get(slug, [])) or "layout / rendered on request"
        lines.append(f"| {schema.get('name', slug)} | `sections/{slug}.liquid` | {blocks_of(schema)} | {ship} |")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    root = os.path.abspath(args.root)
    text = build(root)
    out = os.path.join(root, OUT)
    current = open(out, encoding="utf-8").read() if os.path.exists(out) else None
    if args.check:
        if current != text:
            print(f"sections-index: {OUT} is out of date; run python3 scripts/sections-index.py")
            return 1
        print(f"sections-index: {OUT} up to date")
        return 0
    if current != text:
        open(out, "w", encoding="utf-8").write(text)
        print(f"sections-index: wrote {OUT}")
    else:
        print(f"sections-index: {OUT} already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
